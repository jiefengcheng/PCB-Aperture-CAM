def test_planner_records_rejected_optional_candidate_and_keeps_searching(monkeypatch):
    line=LineString([(0.,0.),(1.,0.)]);core=line.buffer(.025,quad_segs=128)
    rows={'s':{'metadata':dict(minimum_caliper_mm=.05,route_points_mm=list(line.coords),route_kind='segment')}}
    context=SimpleNamespace(ids={'s':('owner',)},cores={'owner':core})
    actual=tp.profile_body;calls=0
    def reject_first(*args,**kwargs):
        nonlocal calls
        calls+=1
        if calls==1:raise tp.ProfileGeometryRejected('controlled optional overlay rejection')
        return actual(*args,**kwargs)
    monkeypatch.setattr(tp,'profile_body',reject_first)
    chosen,_,_,receipt=tp.plan(rows,{'s':core},{'s':core},{'r':['s']},{},context,capture(),{'r':.0125},.1)
    assert calls>1 and chosen['r']['body'].is_valid
    assert len(receipt['candidate_geometry_rejections'])==1
    assert receipt['candidate_geometry_rejections'][0]['route']=='r'


def test_wide_trace_fallback_uses_physical_band_not_progress_as_width_factor():
    settings=capture();obj=object.__new__(tp.Construction)
    obj.settings=settings;obj.targets={'r':.015};obj.maximum={'r':1.5}
    obj.receipt={'scope':'BOUNDED','route_plans':{'r':dict(source_width_mm=.100075,corridor_width_mm=.11,
        outer_width_ceiling_mm=.130075,progress_cap=1.5,construction_floor_profile=dict(
        factor=1.2,corridor_width_mm=.11,outer_width_ceiling_mm=.121))}}
    obj.data={'r':{'width':.100075}};obj.progress=None;obj.profiles=None
    seen=[];accepted=[]
    def check(route,factor):
        seen.append(factor);passed=factor<=1.4
        return dict(passed=passed,failures=[] if passed else [dict(reason='bounded blocker')])
    result=obj.solve({'r':.100075},settings,check,lambda r,f:accepted.append(f),pass_increments=[1,1,1,1,2,2,2])
    assert result['selected_scales']['r']==1.4 and 1.4 in seen
    assert result['pass_increments']==[1,1,1,1,2,2,2]
    decision=result['decisions'][0]
    assert decision['resulting_width_mm']<=.130075
    assert decision['total_width_increase_mm']<=.03
    assert obj.describe_rung('r',10)['resulting_width_mm']==.130075


def test_candidate_neighbor_index_preserves_exhaustive_choices(monkeypatch):
    rows={};original={};ids={};owners={};paths={}
    for r,y in [('a',0.),('b',.09),('c',100.)]:
        line=LineString([(0.,y),(1.,y)]);g=line.buffer(.025,quad_segs=128)
        original[r]=g;rows[r]={'metadata':dict(minimum_caliper_mm=.05,route_points_mm=list(line.coords),route_kind='segment')}
        ids[r]=(r,);owners[r]=g;paths[r]=[r]
    ctx=SimpleNamespace(ids=ids,cores=owners);settings=capture();seed=dict.fromkeys(paths,.0125)
    indexed,_,_,indexed_receipt=tp.plan(rows,original,original,paths,{},ctx,settings,seed,.1)
    monkeypatch.setattr(tp,'candidate_neighbors',lambda paths,data,cores:{r:[s for s in sorted(paths)if s!=r]for r in paths})
    exhaustive,_,_,full_receipt=tp.plan(rows,original,original,paths,{},ctx,settings,seed,.1)
    assert indexed_receipt['route_plans']==full_receipt['route_plans']
    for r in paths:
        assert indexed[r]['pose']==exhaustive[r]['pose']
        assert to_wkb(indexed[r]['body'])==to_wkb(exhaustive[r]['body'])


def test_neighbor_bounds_include_translated_candidates_and_empty_initial_deltas():
    from shapely.geometry import box
    a=box(0.,0.,.02,1.);b=box(.07,0.,.09,1.)
    moved=box(.015,0.,.035,1.)
    data={'a':{'candidates':[dict(body=moved,delta=moved.difference(a))]},
          'b':{'candidates':[dict(body=b,delta=Polygon())]}}
    neighbors=tp.candidate_neighbors({'a':['a'],'b':['b']},data,{'a':a,'b':b})
    assert neighbors=={'a':['b'],'b':['a']}


