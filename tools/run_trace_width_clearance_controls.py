#!/usr/bin/env python3
"""Retain synthetic positive/negative geometry controls, clearly outside C02."""
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
import json,hashlib,subprocess
from shapely.geometry import LineString,box
from shapely.ops import unary_union
from shapely import to_wkb
from src.trace_width_clearance import verify_width_scene
from tools.run_c02_growth_coverage import render


def trace(sid,y=0.,factor=1.5,length=2.):
    route=LineString([(0,y),(length,y)])
    return dict(id=sid,original=route.buffer(.05,quad_segs=128),candidate=route.buffer(.05*factor,quad_segs=128),verified_original_width_mm=.1)


def main():
    out=Path(sys.argv[1]);assert not out.exists();out.mkdir(parents=True)
    cases=[('POSITIVE_ORIGINAL_LAND_ATTACHMENT',[trace('a')],[dict(id='land',geometry=box(-.3,-.2,.3,.2))],True),
        ('NEGATIVE_REMOTE_OBSTACLE',[trace('a',length=30.)],[dict(id='remote',geometry=box(29,.09,31,.2))],False),
        ('NEGATIVE_SIMULTANEOUS_NEIGHBORS',[trace('a'),trace('b',y=.17)],[],False),
        ('POSITIVE_HIDDEN_PRIMITIVE',[trace('a')],[dict(id='land',geometry=box(-.3,-.2,.3,.2)),dict(id='hidden',geometry=box(.05,.055,.2,.07))],True),
        ('NEGATIVE_NEW_BRIDGE',[trace('a'),trace('b',y=.14)],[],False),
        ('POSITIVE_KEEP_INHERITED_GAP',[trace('a',factor=1.)],[dict(id='old',geometry=box(0,.055,2,.2))],True),
        ('NEGATIVE_WORSEN_INHERITED_GAP',[trace('a',factor=1.1)],[dict(id='old',geometry=box(0,.055,2,.2))],False)]
    receipts=[]
    for name,traces,fixed,expected in cases:
        folder=out/name;folder.mkdir()
        check=verify_width_scene(traces,fixed)
        before=unary_union([r['original'] for r in traces]+[r['geometry'] for r in fixed])
        after=unary_union([r['candidate'] for r in traces]+[r['geometry'] for r in fixed])
        (folder/'CHECK.json').write_text(json.dumps(check,indent=2,sort_keys=True)+'\n')
        for label,g in [('before',before),('after',after)]:
            (folder/f'{label}.wkb').write_bytes(to_wkb(g))
        receipts.append(dict(name=name,scope='SYNTHETIC_GEOMETRY_CONTROL_NOT_C02',expected_pass=expected,actual_pass=check['passed'],
            before_wkb_sha256=hashlib.sha256(to_wkb(before)).hexdigest(),after_wkb_sha256=hashlib.sha256(to_wkb(after)).hexdigest(),
            failure_reasons=[r['reason'] for r in check['failures']]))
        assert check['passed']==expected,(name,check)
        if name not in ('POSITIVE_ORIGINAL_LAND_ATTACHMENT','NEGATIVE_NEW_BRIDGE'):continue
        x0,y0,x1,y1=after.bounds;bounds=[x0-.1,y0-.15,x1+.1,y1+.15]
        for label,g in [('before',before),('after',after)]:
            svg=folder/f'{label}.svg'
            notes=[f'SYNTHETIC CONTROL ONLY — not PCB source geometry. Case: {name}.',
                f'Expected pass: {expected}; observed verifier pass: {check["passed"]}. Exact generated control shapes.',
                'Teal = control copper added relative to its synthetic predecessor; red = synthetic union.',
                'Positive: fixed original attachment. Negative: two new widths bridge and must reject.',
                'No C02 copper or acceptance changed. Geometry, checks and hashes are retained beside this image.']
            render(svg,f'SYNTHETIC / {name} / {label}',g,g.difference(before),bounds,[],{},notes)
            text=svg.read_text()
            source_caption='Actual ORG finite-width copper · 850c4c74d55717a7 · source-bound geometric candidate'
            assert text.count(source_caption)==1
            svg.write_text(text.replace(source_caption,'SYNTHETIC finite-width control · generated by deterministic test code · not source PCB'))
            subprocess.run(['sips','-s','format','png',str(svg),'--out',str(folder/f'{label}.png')],check=True,capture_output=True)
    (out/'CONTROL_RECEIPTS.json').write_text(json.dumps(receipts,indent=2,sort_keys=True)+'\n')
    (out/'index.html').write_text('<!doctype html><meta charset="utf-8"><title>Synthetic width controls</title><style>body{font:18px system-ui;margin:24px;color:#142a3f}img{width:100%}</style><h1>Synthetic width verifier controls — not C02</h1><p>Seven expected outcomes reproduced. The negative bridge is deliberately rejected.</p>'+''.join(f'<h2>{name}</h2><img src="{name}/before.png"><img src="{name}/after.png">' for name in ['POSITIVE_ORIGINAL_LAND_ATTACHMENT','NEGATIVE_NEW_BRIDGE']))
    print(json.dumps(dict(controls=len(receipts),all_expected_outcomes=True,scope='SYNTHETIC_ONLY')))


if __name__=='__main__':main()
